#!/usr/bin/env python3
"""Embed the M8 quiz + the M1 Data Traffic Light final-round cards into the quiz Artifact.

Edit quiz_questions.json (questions, final_round.card_ids), then run:
  python3 materials/m8/data/sync_quiz.py
Reads materials/m1/data/traffic_light_cards.json READ-ONLY (M1 owns it).
Writes the <script id="quiz-data"> block in ../artifacts/security-quiz.html
and regenerates ../trainer/answer-key.md (trainer answer key).
"""
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
quiz = json.loads((HERE / "quiz_questions.json").read_text(encoding="utf-8"))
m1 = json.loads((ROOT / quiz["final_round"]["source"]).read_text(encoding="utf-8"))

ids = [q["id"] for q in quiz["questions"]]
assert len(ids) == len(set(ids)), "duplicate question id"
assert 15 <= len(ids) <= 20, f"need 15-20 questions, have {len(ids)}"
for q in quiz["questions"]:
    assert q["cat"] in quiz["categories"], f"{q['id']}: unknown cat"
    assert 0 <= q["answer"] < len(q["options"]), f"{q['id']}: answer out of range"

cards = {c["id"]: c for c in m1["cards"]}
final = [cards[i] for i in quiz["final_round"]["card_ids"]]  # KeyError = id missing in M1

payload = {**quiz, "levels": m1["levels"], "final_cards": final}
block = json.dumps(payload, ensure_ascii=False, indent=1).replace("</", "<\\/")
html_path = HERE.parent / "artifacts" / "security-quiz.html"
page = html_path.read_text(encoding="utf-8")
page, n = re.subn(r'(<script type="application/json" id="quiz-data">\n).*?(\n</script>)',
                  lambda m: m.group(1) + block + m.group(2), page, flags=re.S)
assert n == 1, "quiz-data block not found"
html_path.write_text(page, encoding="utf-8")

letters = "ABCD"
lines = ["# M8 · Answer key (trainer)", "",
         "Generated by `data/sync_quiz.py` from `data/quiz_questions.json`. Do not edit by hand.",
         "The Artifact shuffles option order, so talk about the answer text, not the letter.", "",
         "| ข้อ | หมวด | คำตอบที่ถูก | เหตุผล | ทวนที่ |", "|---|---|---|---|---|"]
for q in quiz["questions"]:
    ans = q["options"][q["answer"]].replace("|", "/")
    lines.append(f"| {q['id']} | {quiz['categories'][q['cat']]} | {letters[q['answer']]}. {ans} | {q['why']} | {q['ref']} |")
lines += ["", "## Final round · Data Traffic Light (การ์ดจาก M1, อ่านอย่างเดียว)", "",
          "| การ์ด | เรื่อง | สี | เหตุผล |", "|---|---|---|---|"]
for c in final:
    lines.append(f"| {c['id']} | {c['title']} | {m1['levels'][c['answer']]} | {c['why']} |")
(HERE.parent / "trainer" / "answer-key.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{html_path}: {len(ids)} questions + {len(final)} final-round cards; trainer/answer-key.md written")
